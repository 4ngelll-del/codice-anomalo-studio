/**
 * Devuelve el resumen ejecutivo de las 52 semanas (1,092 carruseles / 5,460 diapositivas)
 */
export function getAnnualSummary() {
  const weeksIndex = Array.from({ length: 52 }, (_, i) => {
    const w = i + 1;
    const monthIdx = Math.min(11, Math.floor((w - 1) / 4.34));
    const m = ANNUAL_MONTH_THEMES[monthIdx];
    const startDossier = (w - 1) * 21 + 1;
    const endDossier = w * 21;
    return {
      weekNumber: w,
      monthNumber: m.month,
      monthName: m.name,
      theme: m.theme,
      carouselsCount: 21,
      slidesCount: 105,
      dossierRange: `#CA-${String(startDossier).padStart(4, '0')} — #CA-${String(endDossier).padStart(4, '0')}`
    };
  });

  return {
    totalWeeks: 52,
    totalDays: 364,
    postsPerDay: 3,
    schedulesCDMX: ['09:00', '15:00', '21:00'],
    totalCarousels: 1092,
    totalSlides: 5460,
    totalArchetypes: ARCHETYPE_KEYS.length,
    archetypes: VIRAL_ARCHETYPES,
    monthlyThemes: ANNUAL_MONTH_THEMES,
    weeksIndex
  };
}
