    const seedIndex = (globalPostNumber - 1) % totalSeeds;
    const modifierIndex = Math.floor((globalPostNumber - 1) / totalSeeds) % WEEKLY_ANGLE_MODIFIERS.length;
    const baseCase = MASTER_CASE_LIBRARY[seedIndex];
    const modifier = WEEKLY_ANGLE_MODIFIERS[modifierIndex];

